// Positional astronomy for the sky over Chandigarh.
//
// Everything in the sky is where it would really be for the game's date, time
// and site: the Sun and Moon from the Astronomical Almanac's low-precision
// series (good to a few tenths of a degree), the stars from J2000 coordinates
// precessed to the epoch of date, all rotated into the local horizon frame by
// sidereal time. World axes: +X east, +Y up, +Z south.
import { THREE } from './lib/three.js';
import { DEG, TAU, mod, clamp } from './util.js';

export const SITE = { name: 'Chandigarh', lat: 30.7333, lon: 76.7794, tz: 5.5 };

// Julian Date from a Gregorian calendar date (valid 1901-2099) and UT hours.
export function julianDate(y, m, d, hoursUT = 0) {
  return 367 * y - Math.floor((7 * (y + Math.floor((m + 9) / 12))) / 4) + Math.floor((275 * m) / 9) + d + 1721013.5 + hoursUT / 24;
}
export const jdFromLocal = (y, m, d, hoursLocal, tz = SITE.tz) => julianDate(y, m, d, hoursLocal - tz);

// Local civil time (hours, 0-24) for a Julian Date.
export function localHours(jd, tz = SITE.tz) {
  return mod((jd + 0.5 + tz / 24) % 1, 1) * 24;
}

// Calendar date (local) from a Julian Date, for the HUD clock.
export function localCalendar(jd, tz = SITE.tz) {
  const z = Math.floor(jd + 0.5 + tz / 24);
  const a = Math.floor((z - 1867216.25) / 36524.25);
  const A = z + 1 + a - Math.floor(a / 4);
  const B = A + 1524;
  const C = Math.floor((B - 122.1) / 365.25);
  const D = Math.floor(365.25 * C);
  const E = Math.floor((B - D) / 30.6001);
  const day = B - D - Math.floor(30.6001 * E);
  const month = E < 14 ? E - 1 : E - 13;
  const year = month > 2 ? C - 4716 : C - 4715;
  return { year, month, day };
}

function sunEcliptic(d) {
  const L = mod(280.46 + 0.9856474 * d, 360);
  const g = mod(357.528 + 0.9856003 * d, 360) * DEG;
  return { lambda: (L + 1.915 * Math.sin(g) + 0.02 * Math.sin(2 * g)) * DEG, g };
}

function eclipticToEquatorial(lambda, beta, eps, out) {
  const cb = Math.cos(beta), sb = Math.sin(beta), cl = Math.cos(lambda), sl = Math.sin(lambda);
  const ce = Math.cos(eps), se = Math.sin(eps);
  // unit vector in the equatorial frame (x to the equinox, z to the pole)
  out.set(cb * cl, ce * cb * sl - se * sb, se * cb * sl + ce * sb);
  return out;
}

function moonEcliptic(T) {
  const s = a => Math.sin(a * DEG), c = a => Math.cos(a * DEG);
  const lambda = 218.32 + 481267.881 * T
    + 6.29 * s(135.0 + 477198.87 * T) - 1.27 * s(259.3 - 413335.36 * T)
    + 0.66 * s(235.7 + 890534.22 * T) + 0.21 * s(269.9 + 954397.74 * T)
    - 0.19 * s(357.5 + 35999.05 * T) - 0.11 * s(186.5 + 966404.03 * T);
  const beta = 5.13 * s(93.3 + 483202.02 * T) + 0.28 * s(228.2 + 960400.89 * T)
    - 0.28 * s(318.3 + 6003.15 * T) - 0.17 * s(217.6 - 407332.21 * T);
  const parallax = 0.9508 + 0.0518 * c(135.0 + 477198.87 * T) + 0.0095 * c(259.3 - 413335.36 * T)
    + 0.0078 * c(235.7 + 890534.22 * T) + 0.0028 * c(269.9 + 954397.74 * T);
  return { lambda: mod(lambda, 360) * DEG, beta: beta * DEG, parallax: parallax * DEG };
}

// Rotation taking J2000 equatorial vectors to the mean equator and equinox of date.
function precessionMatrix(T, m) {
  const as = Math.PI / 648000; // arcseconds to radians
  const zeta = (2306.2181 * T + 0.30188 * T * T + 0.017998 * T * T * T) * as;
  const z = (2306.2181 * T + 1.09468 * T * T + 0.018203 * T * T * T) * as;
  const theta = (2004.3109 * T - 0.42665 * T * T - 0.041833 * T * T * T) * as;
  const cz = Math.cos(zeta), sz = Math.sin(zeta), cZ = Math.cos(z), sZ = Math.sin(z), ct = Math.cos(theta), st = Math.sin(theta);
  m.set(
    cz * ct * cZ - sz * sZ, -sz * ct * cZ - cz * sZ, -st * cZ, 0,
    cz * ct * sZ + sz * cZ, -sz * ct * sZ + cz * cZ, -st * sZ, 0,
    cz * st, -sz * st, ct, 0,
    0, 0, 0, 1);
  return m;
}

// Rotation taking equatorial-of-date vectors to the local horizon (world) frame.
function horizonMatrix(lst, lat, m) {
  const cl = Math.cos(lst), sl = Math.sin(lst), cp = Math.cos(lat), sp = Math.sin(lat);
  m.set(
    -sl, cl, 0, 0,
    cl * cp, sl * cp, sp, 0,
    cl * sp, sl * sp, -cp, 0,
    0, 0, 0, 1);
  return m;
}

// Bennett's refraction formula; lifts things near the horizon by about half a degree.
function refract(alt) {
  const h = alt / DEG;
  if (h < -1.5) return alt;
  const R = 1.02 / Math.tan((h + 10.3 / (h + 5.11)) * DEG); // arcminutes
  return alt + (R / 60) * DEG;
}

const _v = new THREE.Vector3();
const _m1 = new THREE.Matrix4();
const _m2 = new THREE.Matrix4();

export class Astro {
  constructor(site = SITE) {
    this.site = site;
    this.jd = 2451545;
    this.sunDir = new THREE.Vector3(0, 1, 0);     // unit vectors toward each body, world frame
    this.moonDir = new THREE.Vector3(0, 1, 0);
    this.sunAlt = 0; this.sunAz = 0; this.moonAlt = 0; this.moonAz = 0;
    this.moonPhase = 0;        // illuminated fraction, 0 new .. 1 full
    this.moonWaxing = true;
    this.lst = 0;              // local sidereal time, radians
    this.starMatrix = new THREE.Matrix4();    // J2000 equatorial -> world
    this.poleDir = new THREE.Vector3();        // north celestial pole, world frame
    this.hours = 0;            // local civil time
  }

  setLocal(y, m, d, hours) { this.update(jdFromLocal(y, m, d, hours, this.site.tz)); return this; }

  update(jd) {
    this.jd = jd;
    const d = jd - 2451545.0;
    const T = d / 36525;
    const eps = (23.439 - 0.0000004 * d) * DEG;
    const gmst = mod(280.46061837 + 360.98564736629 * d, 360) * DEG;
    const lst = mod(gmst + this.site.lon * DEG, TAU);
    const lat = this.site.lat * DEG;
    this.lst = lst;
    this.hours = localHours(jd, this.site.tz);
    horizonMatrix(lst, lat, _m1);

    // Sun
    const sun = sunEcliptic(d);
    eclipticToEquatorial(sun.lambda, 0, eps, _v).applyMatrix4(_m1);
    this._place(_v, this.sunDir, 0);
    this.sunAlt = Math.asin(clamp(this.sunDir.y, -1, 1));
    this.sunAz = mod(Math.atan2(this.sunDir.x, -this.sunDir.z), TAU);

    // Moon (with topocentric parallax, which matters at about a degree)
    const moon = moonEcliptic(T);
    eclipticToEquatorial(moon.lambda, moon.beta, eps, _v).applyMatrix4(_m1);
    this._place(_v, this.moonDir, moon.parallax);
    this.moonAlt = Math.asin(clamp(this.moonDir.y, -1, 1));
    this.moonAz = mod(Math.atan2(this.moonDir.x, -this.moonDir.z), TAU);
    const elong = mod(moon.lambda - sun.lambda, TAU);
    this.moonPhase = (1 - Math.cos(elong) * Math.cos(moon.beta)) / 2;
    this.moonWaxing = elong < Math.PI;
    this.moonAge = (elong / TAU) * 29.530588;

    // Stars: J2000 -> of date -> horizon
    precessionMatrix(T, _m2);
    this.starMatrix.multiplyMatrices(_m1, _m2);
    this.poleDir.set(0, 0, 1).applyMatrix4(_m1);
    return this;
  }

  // Apply parallax and refraction to a geometric horizon-frame direction.
  _place(v, out, parallax) {
    let alt = Math.asin(clamp(v.y, -1, 1));
    const az = Math.atan2(v.x, -v.z);
    if (parallax) alt -= parallax * Math.cos(alt);
    alt = refract(alt);
    const ca = Math.cos(alt);
    out.set(ca * Math.sin(az), Math.sin(alt), -ca * Math.cos(az));
  }

  // Convert a J2000 right ascension (hours) and declination (degrees) to a world direction.
  starDir(raHours, decDeg, out = new THREE.Vector3()) {
    const ra = raHours * 15 * DEG, dec = decDeg * DEG;
    return out.set(Math.cos(dec) * Math.cos(ra), Math.cos(dec) * Math.sin(ra), Math.sin(dec)).applyMatrix4(this.starMatrix);
  }
}

